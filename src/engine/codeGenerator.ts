import type { ConditionRule, IndicatorOperand, StrategySpec } from '../types/quant';

function toPineOperand(op: IndicatorOperand): string {
  switch (op.kind) {
    case 'CLOSE':
      return 'close';
    case 'VOLUME':
      return 'volume';
    case 'CONST':
      return `${op.value ?? 0}`;
    case 'SMA':
      return `ta.sma(close, ${op.period ?? 20})`;
    case 'EMA':
      return `ta.ema(close, ${op.period ?? 20})`;
    case 'VWAP':
      return `ta.vwap(hlc3)`;
    case 'RSI':
      return `ta.rsi(close, ${op.period ?? 14})`;
    case 'ADX':
      return `ta.dmi(${op.period ?? 14}, ${op.period ?? 14})[2]`;
    case 'ATR':
      return `ta.atr(${op.period ?? 14})`;
    case 'STOCH_K':
      return `ta.stoch(close, high, low, ${op.period ?? 14})`;
    case 'VOLUME_SMA':
      return `ta.sma(volume, ${op.period ?? 20})`;
    case 'MACD_LINE':
      return `macdLine`;
    case 'MACD_SIGNAL':
      return `signalLine`;
    case 'MACD_HIST':
      return `histLine`;
    case 'BB_UPPER':
      return `bbUpper`;
    case 'BB_MIDDLE':
      return `bbBasis`;
    case 'BB_LOWER':
      return `bbLower`;
  }
}

function toPineRule(rule: ConditionRule): string {
  const l = toPineOperand(rule.left);
  const r = toPineOperand(rule.right);
  switch (rule.operator) {
    case 'CROSS_ABOVE':
      return `ta.crossover(${l}, ${r})`;
    case 'CROSS_BELOW':
      return `ta.crossunder(${l}, ${r})`;
    case 'GREATER_THAN':
      return `(${l} > ${r})`;
    case 'LESS_THAN':
      return `(${l} < ${r})`;
  }
}

export function generatePineScript(strategy: StrategySpec): string {
  const allRules = [...strategy.entryRules, ...strategy.exitRules].filter((r) => r.enabled);
  const ops = allRules.flatMap((r) => [r.left, r.right]);

  const usesMacd = ops.some((o) => o.kind.startsWith('MACD_'));
  const usesBb = ops.some((o) => o.kind.startsWith('BB_'));
  const macdOp = ops.find((o) => o.kind.startsWith('MACD_'));
  const bbOp = ops.find((o) => o.kind.startsWith('BB_'));

  const lines: string[] = [
    `//@version=5`,
    `// Generated by QuantBlock No-Code Algo Builder`,
    `strategy("${strategy.name}", overlay=true, initial_capital=${strategy.execution.initialCapital}, default_qty_type=strategy.percent_of_equity, default_qty_value=${strategy.execution.positionSizePct}, commission_type=strategy.commission.percent, commission_value=${(strategy.execution.feeBps / 100).toFixed(3)})`,
    ``,
  ];

  if (usesMacd) {
    lines.push(
      `[macdLine, signalLine, histLine] = ta.macd(close, ${macdOp?.fastPeriod ?? 12}, ${macdOp?.slowPeriod ?? 26}, ${macdOp?.signalPeriod ?? 9})`
    );
  }
  if (usesBb) {
    lines.push(
      `[bbBasis, bbUpper, bbLower] = ta.bb(close, ${bbOp?.period ?? 20}, ${bbOp?.stdDev ?? 2})`
    );
  }
  if (usesMacd || usesBb) lines.push('');

  const entryExprs = strategy.entryRules.filter((r) => r.enabled).map(toPineRule);
  const exitExprs = strategy.exitRules.filter((r) => r.enabled).map(toPineRule);

  const entryJoin = strategy.entryLogic === 'AND' ? ' and ' : ' or ';
  const exitJoin = strategy.exitLogic === 'AND' ? ' and ' : ' or ';

  lines.push(`entryCond = ${entryExprs.length > 0 ? entryExprs.join(entryJoin) : 'false'}`);
  lines.push(`exitCond  = ${exitExprs.length > 0 ? exitExprs.join(exitJoin) : 'false'}`);
  lines.push('');
  lines.push(`if entryCond and strategy.position_size == 0`);
  lines.push(`    strategy.entry("Long", strategy.long)`);

  if (strategy.execution.stopLossPct > 0 || strategy.execution.takeProfitPct > 0) {
    const sl =
      strategy.execution.stopLossPct > 0
        ? `strategy.position_avg_price * ${(1 - strategy.execution.stopLossPct / 100).toFixed(4)}`
        : 'na';
    const tp =
      strategy.execution.takeProfitPct > 0
        ? `strategy.position_avg_price * ${(1 + strategy.execution.takeProfitPct / 100).toFixed(4)}`
        : 'na';
    lines.push('');
    lines.push(`if strategy.position_size > 0`);
    lines.push(`    strategy.exit("RiskMgmt", from_entry="Long", stop=${sl}, limit=${tp})`);
  }

  lines.push('');
  lines.push(`if exitCond and strategy.position_size > 0`);
  lines.push(`    strategy.close("Long", comment="Signal Exit")`);

  return lines.join('\n');
}

function toPythonOperand(op: IndicatorOperand): string {
  switch (op.kind) {
    case 'CLOSE':
      return `df["close"]`;
    case 'VOLUME':
      return `df["volume"]`;
    case 'CONST':
      return `${op.value ?? 0}`;
    case 'SMA':
      return `df["close"].rolling(${op.period ?? 20}).mean()`;
    case 'EMA':
      return `df["close"].ewm(span=${op.period ?? 20}, adjust=False).mean()`;
    case 'VWAP':
      return `calc_vwap(df)`;
    case 'RSI':
      return `calc_rsi(df["close"], ${op.period ?? 14})`;
    case 'ADX':
      return `calc_adx(df, ${op.period ?? 14})`;
    case 'ATR':
      return `calc_atr(df, ${op.period ?? 14})`;
    case 'STOCH_K':
      return `calc_stoch_k(df, ${op.period ?? 14})`;
    case 'VOLUME_SMA':
      return `df["volume"].rolling(${op.period ?? 20}).mean()`;
    case 'MACD_LINE':
      return `macd_line`;
    case 'MACD_SIGNAL':
      return `macd_signal`;
    case 'MACD_HIST':
      return `macd_hist`;
    case 'BB_UPPER':
      return `bb_upper`;
    case 'BB_MIDDLE':
      return `bb_mid`;
    case 'BB_LOWER':
      return `bb_lower`;
  }
}

function toPythonRule(rule: ConditionRule): string {
  const l = toPythonOperand(rule.left);
  const r = toPythonOperand(rule.right);
  switch (rule.operator) {
    case 'CROSS_ABOVE':
      return `crossover(${l}, ${r})`;
    case 'CROSS_BELOW':
      return `crossunder(${l}, ${r})`;
    case 'GREATER_THAN':
      return `(${l} > ${r})`;
    case 'LESS_THAN':
      return `(${l} < ${r})`;
  }
}

export function generatePythonScript(strategy: StrategySpec): string {
  const entryExprs = strategy.entryRules.filter((r) => r.enabled).map(toPythonRule);
  const exitExprs = strategy.exitRules.filter((r) => r.enabled).map(toPythonRule);
  const entryJoin = strategy.entryLogic === 'AND' ? ' & ' : ' | ';
  const exitJoin = strategy.exitLogic === 'AND' ? ' & ' : ' | ';

  return `# Generated by QuantBlock No-Code Algo Builder
import pandas as pd
import numpy as np

def crossover(a: pd.Series, b):
    b_s = b if isinstance(b, pd.Series) else pd.Series(b, index=a.index)
    return (a.shift(1) <= b_s.shift(1)) & (a > b_s)

def crossunder(a: pd.Series, b):
    b_s = b if isinstance(b, pd.Series) else pd.Series(b, index=a.index)
    return (a.shift(1) >= b_s.shift(1)) & (a < b_s)

def build_signals(df: pd.DataFrame) -> pd.DataFrame:
    """
    Strategy: ${strategy.name}
    Symbol: ${strategy.symbol} (${strategy.timeframe})
    Risk: SL=${strategy.execution.stopLossPct}%, TP=${strategy.execution.takeProfitPct}%, Fee=${strategy.execution.feeBps}bps
    """
    ema12 = df["close"].ewm(span=12, adjust=False).mean()
    ema26 = df["close"].ewm(span=26, adjust=False).mean()
    macd_line = ema12 - ema26
    macd_signal = macd_line.ewm(span=9, adjust=False).mean()
    macd_hist = macd_line - macd_signal

    bb_mid = df["close"].rolling(20).mean()
    bb_std = df["close"].rolling(20).std()
    bb_upper = bb_mid + 2.0 * bb_std
    bb_lower = bb_mid - 2.0 * bb_std

    df["entry_signal"] = ${entryExprs.length > 0 ? entryExprs.join(entryJoin) : 'False'}
    df["exit_signal"]  = ${exitExprs.length > 0 ? exitExprs.join(exitJoin) : 'False'}
    return df
`;
}
